import json
import urllib.request


def load_voice_engine():
    return{
        "url":"http://127.0.0.1:8001"
    }

def synthesize_pcm(engine, text, language):

    if not text.strip():
        return b""

    lang_key = "ja" if language.lower().startswith("ja") else "en"

    payload = {
        "text": text,
        "language": lang_key,
    }

    body = json.dumps(payload).encode("utf-8")

    request = urllib.request.Request(
        engine["url"] + "/synthesize",
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    #the server generates the speech here.

    with urllib.request.urlopen(request, timeout=300) as response:
        content_type = response.headers.get_content_type()

        if content_type != "application/octet-stream":
            raise RuntimeError(
                f"Unexpected content type: {content_type}"
            )

        pcm = response.read()

    if not pcm or len(pcm) % 2 != 0:
        raise RuntimeError("Received empty or incomplete PCM audio")

    return pcm
if __name__ == "__main__":
    import wave

    engine = load_voice_engine()

    pcm = synthesize_pcm(
        engine,
        "Hello. My name is G1.",
        "en",
    )

    with wave.open("voice_test.wav", "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(16000)
        output.writeframes(pcm)

    print("Generated bytes:", len(pcm))
    print("Saved voice_test.wav")